const SVG = "http://www.w3.org/2000/svg"

/** A Lucide icon as an <svg> element. `filled` matches the web player's filled play and pause. */
export function icon(name, { filled = false } = {}) {
  const svg = document.createElementNS(SVG, "svg")
  for (const [key, value] of Object.entries({
    viewBox: "0 0 24 24", fill: filled ? "currentColor" : "none", stroke: "currentColor", "stroke-width": "2",
    "stroke-linecap": "round", "stroke-linejoin": "round", "aria-hidden": "true",
  })) svg.setAttribute(key, value)
  for (const [tag, attributes] of nodes[name] ?? []) {
    const child = document.createElementNS(SVG, tag)
    for (const [key, value] of Object.entries(attributes)) child.setAttribute(key, value)
    svg.append(child)
  }
  return svg
}

/** Fills every `<span data-icon="name">` (add `data-filled` for a solid icon) with its Lucide icon. */
export function hydrate(root = document) {
  for (const element of root.querySelectorAll("[data-icon]")) {
    element.replaceChildren(icon(element.dataset.icon, { filled: element.hasAttribute("data-filled") }))
  }
}
